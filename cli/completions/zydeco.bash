            if [[ ${cur} == -* || ${COMP_CWORD} -eq 2 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                --pkg)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                --package)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                -p)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                --target-os)
                    COMPREPLY=($(compgen -W "linux macos" -- "${cur}"))
                    return 0
                    ;;
                --target-arch)
                    COMPREPLY=($(compgen -W "x86-64 aarch64" -- "${cur}"))
                    return 0
                    ;;
                --target)
                    COMPREPLY=($(compgen -W "zir zasm asm object staticlib sharedlib wasm-am wasm-sps exe" -- "${cur}"))
                    return 0
                    ;;
                -t)
                    COMPREPLY=($(compgen -W "zir zasm asm object staticlib sharedlib wasm-am wasm-sps exe" -- "${cur}"))
                    return 0
                    ;;
                --representation)
                    COMPREPLY=($(compgen -W "boxed direct local shared" -- "${cur}"))
                    return 0
                    ;;
                --sps-passes)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                --build-dir)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                -b)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                --runtime-dir)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                -r)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                --link-library)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                *)
                    COMPREPLY=()
                    ;;
            esac
            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
        zydeco__subcmd__check)
            opts="-p -h --package --pkg --lint-types --help"
